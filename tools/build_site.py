"""Assemble the exported teaching gallery for GitHub Pages using only stdlib.

Run ``python3 tools/build_site.py`` from any directory. The generated ``_site``
folder preserves relative links, so it works under /dna_animations/ or any other
project path. Rendering and rebuilding the source gallery are separate steps;
deployment never imports Manim or installs Python dependencies.
"""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path
import runpy
import shutil
import sys
from urllib.parse import unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
MARKER = ".dna-animations-site"
MARKER_TEXT = "Generated by tools/build_site.py; safe to rebuild.\n"
REDIRECT = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="refresh" content="0; url=previews/">
<title>DNA methods · Animation library</title>
<style>body{margin:3rem;background:#f5f5f2;color:#242823;font:18px/1.5 system-ui,sans-serif}a{color:#527569}</style>
</head><body><p><a href="previews/">Open the DNA animation library</a></p></body></html>
"""


class LocalReferences(HTMLParser):
    """Include the GIF/poster URLs used dynamically by the gallery controls."""

    def __init__(self):
        super().__init__()
        self.urls: list[str] = []
        self.gifs: set[str] = set()

    def handle_starttag(self, tag, attrs):
        for key, value in attrs:
            if key in {"href", "src", "poster", "data-gif", "data-poster"} and value:
                self.urls.append(value)
                if key == "data-gif":
                    self.gifs.add(unquote(urlsplit(value).path))


def read_catalog(root: Path):
    # Importing dna_animations would import its Manim-based __init__.py.
    # The catalogue is intentionally a standalone, dependency-free module.
    lessons = runpy.run_path(str(root / "dna_animations/catalog.py"))["LESSONS"]
    names = [row[0] for row in lessons]
    if not names or len(names) != len(set(names)):
        raise ValueError("The lesson catalogue must contain unique scene names")
    return lessons


def source_files(root: Path, lessons) -> set[Path]:
    files = {Path("previews/index.html"), Path("docs/visual_language.md")}
    for name, _module, _family, notes in lessons:
        files.update({
            Path("previews/v5") / f"{name}.gif",
            Path("previews/posters") / f"{name}.jpg",
            Path("media/videos/scenes/720p30") / f"{name}.mp4",
            Path("docs") / f"{notes}.md",
        })
    missing = [str(path) for path in sorted(files) if not (root / path).is_file()]
    if missing:
        raise FileNotFoundError(
            "Missing committed exports; render/export and rebuild the gallery first:\n  "
            + "\n  ".join(missing)
        )
    return files


def validate_links(site: Path) -> int:
    """Check local HTML links, including cache-busting queries and GIF data URLs."""
    checked: set[Path] = set()
    for page in site.rglob("*.html"):
        parser = LocalReferences()
        parser.feed(page.read_text(encoding="utf-8"))
        for url in parser.urls:
            parts = urlsplit(url)
            if parts.scheme or parts.netloc or not parts.path:
                continue
            if parts.path.startswith("/"):
                raise ValueError(f"Use a relative project-site URL in {page}: {url}")
            target = (page.parent / unquote(parts.path)).resolve()
            if not target.is_relative_to(site):
                raise ValueError(f"Link escapes the site in {page}: {url}")
            if target.is_dir():
                target = target / "index.html"
            if not target.is_file():
                raise FileNotFoundError(f"Broken local link in {page}: {url}")
            checked.add(target)
    return len(checked)


def build_site(root: Path, output: Path) -> tuple[int, int, int]:
    root, output = root.resolve(), output.resolve()
    lessons = read_catalog(root)
    files = source_files(root, lessons)
    gallery = LocalReferences()
    gallery.feed((root / "previews/index.html").read_text(encoding="utf-8"))
    expected = {f"v5/{row[0]}.gif" for row in lessons}
    if gallery.gifs != expected:
        raise ValueError("The gallery differs from the catalogue; run tools/build_gallery.py first")

    # Never erase a source directory or an unrelated destination. Only a folder
    # produced by this tool may be cleaned to remove stale published assets.
    if output == root or output in root.parents:
        raise ValueError("The output must be a dedicated generated directory")
    if output.exists():
        marker = output / MARKER
        if not output.is_dir() or (any(output.iterdir()) and (
            not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER_TEXT
        )):
            raise ValueError(f"Refusing to replace a directory not generated by this tool: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    for relative in sorted(files):
        destination = output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Copy bytes, not symlinks/hardlinks; Pages artifacts must contain files.
        shutil.copy2(root / relative, destination)
    (output / "index.html").write_text(REDIRECT, encoding="utf-8")
    checked = validate_links(output)
    size = sum(path.stat().st_size for path in output.rglob("*") if path.is_file())
    return len(lessons), checked, size


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "_site",
                        help="Generated site directory (default: project/_site)")
    args = parser.parse_args()
    try:
        count, checked, size = build_site(ROOT, args.output)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"Site build failed: {error}\n")
    print(f"Built {count} lessons: {args.output.resolve()}")
    print(f"Verified {checked} local link targets; bundle size {size / 1024**2:.1f} MiB")


if __name__ == "__main__":
    main()
